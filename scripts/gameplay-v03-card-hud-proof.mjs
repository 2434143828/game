import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { chromium } from '@playwright/test';

const output = `docs/gameplay-v03-evidence/card-hud-${new Date().toISOString().replaceAll(':', '-')}`;
await mkdir(output, { recursive: true });
const report = { status: 'RUNNING', method: 'Explicit no-save card art fixture; native UI input; read-only simulation observations. No injected cards, time, damage or positions.', checks: [], inputs: [], errors: [] };
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1600, height: 900 } });
const page = await context.newPage();
page.on('pageerror', e => report.errors.push(String(e)));
const click = async selector => { report.inputs.push(selector); await page.locator(selector).click(); };
const read = () => page.evaluate(() => structuredClone(window.__v3Test.simulation.state));
const shot = async name => page.screenshot({ path: `${output}/${name}.png` });
const hash = b => createHash('sha256').update(b).digest('hex');
try {
  const loadedCards = [];
  for (const group of ['T', 'N01', 'N02', 'N03', 'N04', 'N05']) {
    await page.goto(`http://127.0.0.1:4173/?cardArtPreview=${group}`, { waitUntil: 'networkidle' });
    await page.waitForFunction(() => window.__v3Test?.scene.getViewState().employees?.length === 3);
    await page.waitForFunction(() => { const images = [...document.querySelectorAll('#v3-hand .v3-card-art img')]; return images.length === 3 && images.every(image => image.complete && image.naturalWidth > 0); });
    const images = await page.locator('#v3-hand .v3-card-art img').evaluateAll(es => es.map(e => ({ cardId: e.closest('[data-card-id]').dataset.cardId, source: e.getAttribute('src'), width: e.naturalWidth, height: e.naturalHeight })));
    assert.equal(images.length, 3);
    loadedCards.push(...images);
    await shot(`00-art-${group.toLowerCase()}`);
  }
  assert.equal(new Set(loadedCards.map(card => card.cardId)).size, 18);
  report.checks.push({ name: 'All 18 generated card illustrations loaded in actual game', loadedCards });
  await page.goto('http://127.0.0.1:4173/?cardArtPreview=N01', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => window.__v3Test?.scene.getViewState().employees?.length === 3);
  assert.equal(await page.locator('[data-v3="card"]').count(), 3);
  const normal = page.locator('[data-card-id="N01_1"]'), locked = page.locator('[data-card-id="N01_3"]');
  assert.equal(await locked.getAttribute('data-card-state'), 'unavailable');
  assert.match(await locked.locator('.v3-card-state').textContent(), /尚无可复制/);
  const node = await normal.elementHandle();
  await shot('01-portrait-hand');
  await normal.hover();
  assert.equal(await page.locator('.v3-card-preview').isVisible(), true);
  assert.match(await page.locator('.v3-card-preview').textContent(), /造成14白伤/);
  await shot('02-hover-preview');
  await normal.click();
  await page.mouse.move(1200, 100);
  await page.waitForTimeout(80);
  const selected = await page.evaluate(() => window.__v3Test.scene.getViewState().cards);
  report.checks.push({ name: 'Selected real owner and valid targets', selected });
  await shot('02b-selected-owner-targets');
  const enemy = (await read()).encounter.enemies[0];
  const point = await page.evaluate(id => window.__v3Test.scene.getEnemyTargetPoint(id), enemy.id);
  await page.mouse.click(point.x, point.y);
  assert.equal((await read()).encounter.deck.pendingCast?.targetId, enemy.id);
  await shot('03-paused-queued');
  const before = await read(), pausedImage = await page.screenshot();
  await page.waitForTimeout(700);
  assert.deepEqual(await read(), before);
  assert.equal(hash(await page.screenshot()), hash(pausedImage), 'Paused visuals changed without input');
  report.checks.push('Paused queued cast: full simulation and screenshot unchanged for 700 ms');
  assert(await node.evaluate((el) => el === document.querySelector('[data-card-id="N01_1"]')), 'Card button was recreated');
  await click('[data-v3="pause"]');
  await page.waitForFunction(() => window.__v3Test.simulation.state.logs.some(e => e.kind === 'CARD' && e.cardId === 'N01_1'), undefined, { timeout: 10000 });
  await click('[data-v3="pause"]');
  await page.mouse.move(1200, 100);
  const cooldown = await read();
  assert(cooldown.encounter.deck.globalCooldown > 0);
  assert(cooldown.encounter.deck.discardPile.some(c => c.cardId === 'N01_1'));
  assert.equal(await page.locator('.v3-card-flight[data-card-id="N01_1"]').count(), 1, 'Successful cast did not display real card flight');
  const remaining = page.locator('[data-card-id="N01_2"]');
  assert.equal(await remaining.getAttribute('data-card-state'), 'cooldown');
  const cut = await remaining.evaluate(el => Number.parseFloat(el.style.getPropertyValue('--cooldown-cut')));
  assert(cut >= 0 && cut < 40);
  const overlayStyle = await remaining.locator('.v3-card-cooldown').evaluate(el => ({ filter: getComputedStyle(el).backdropFilter, clip: getComputedStyle(el).clipPath }));
  assert.match(overlayStyle.filter, /grayscale\(1\)/);
  await shot('04-cast-cooldown-start');
  const frozen = await page.screenshot();
  await page.waitForTimeout(500);
  assert.equal(hash(await page.screenshot()), hash(frozen), 'Cooldown or flight advanced during pause');
  await click('[data-v3="pause"]');
  await page.waitForFunction(() => { const c = window.__v3Test.simulation.state.encounter.deck.globalCooldown; return c > 0.9 && c < 1.3; });
  await click('[data-v3="pause"]');
  await page.mouse.move(1200, 100);
  const middle = await remaining.evaluate(el => Number.parseFloat(el.style.getPropertyValue('--cooldown-cut')));
  assert(middle > 45 && middle < 75);
  await shot('05-cooldown-top-half-color');
  await remaining.screenshot({ path: `${output}/05b-real-card-cooldown-detail.png` });
  report.checks.push({ name: 'Full-card grayscale top-to-bottom restore', initialCutPercent: cut, halfwayCutPercent: middle, overlayStyle });
  await click('[data-v3="pause"]');
  await page.waitForFunction(() => window.__v3Test.simulation.state.encounter.deck.globalCooldown <= 0);
  await click('[data-v3="pause"]');
  assert.equal(await remaining.getAttribute('data-card-state'), 'available');
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.mouse.move(1100, 70);
  await shot('06-1280-readable');
  for (const box of await page.locator('[data-v3="card"]').evaluateAll(es => es.map(e => e.getBoundingClientRect().toJSON()))) {
    assert(box.left >= 0 && box.right <= 1280 && box.bottom <= 720);
  }
  report.checks.push('1280 x 720: all hand cards inside viewport');
  assert.deepEqual(report.errors, []);
  report.status = 'PASS';
} catch (e) { report.status = 'FAIL'; report.reason = String(e.stack ?? e); }
finally { await context.close(); await browser.close(); await writeFile(`${output}/report.json`, JSON.stringify(report, null, 2)); console.log(JSON.stringify({ output, ...report }, null, 2)); if (report.status !== 'PASS') process.exitCode = 1; }
